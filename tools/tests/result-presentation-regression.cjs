const assert=require('node:assert/strict'), fs=require('node:fs')
const {transformSync}=require('../../web/node_modules/rolldown/dist/utils-index.mjs')
const result=transformSync('result.ts',fs.readFileSync('web/src/center/resultPresentation.ts','utf8'),{target:'es2022'})
const {localPlacement,celebrationTitle}=new Function(result.code.replace(/\bexport\s+/g,'')+'\nreturn {localPlacement,celebrationTitle};')()
assert.equal(localPlacement([{who:'ALICE',rank:9}],'alice'),9)
assert.equal(localPlacement([{who:'alice',rank:1}],'spectator'),undefined)
assert.equal(localPlacement([{who:'alice',rank:1}],'alice',{alice:'crew'},[{team:'crew',rank:4}]),4)
assert.equal(localPlacement([{who:'alice',rank:NaN}],'alice'),undefined)
assert.equal(celebrationTitle('Alice',9),'You placed #9')
assert.equal(celebrationTitle('Alice',1),'Congratulations, Alice!')
assert.equal(celebrationTitle('Alice'),'Congratulations, Alice!')
console.log('7 result presentation regressions passed.')
